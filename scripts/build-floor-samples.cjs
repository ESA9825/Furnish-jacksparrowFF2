/* Generate lazy classic scripts for origin-clean textures when opening file://. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const base=path.resolve(__dirname,'../assets/materials/floors'),sources=require(path.join(base,'sources.json'));
for(const [id,source] of Object.entries(sources)){
 const directory=path.join(base,id),data={};
 for(const [file,{sha256}] of Object.entries(source.maps)){
  const bytes=fs.readFileSync(path.join(directory,file));
  if(createHash('sha256').update(bytes).digest('hex')!==sha256)throw Error('Floor source hash mismatch: '+id+'/'+file);
  data[file]='data:image/jpeg;base64,'+bytes.toString('base64');
 }
 fs.writeFileSync(path.join(directory,'offline.js'),
  '/* Generated by scripts/build-floor-samples.cjs from the original CC0 JPEGs. */\n'+
  '(globalThis.FurnishFloorSampleImages??=Object.create(null))['+JSON.stringify(id)+'] = '+JSON.stringify(data,null,2)+';\n');
}

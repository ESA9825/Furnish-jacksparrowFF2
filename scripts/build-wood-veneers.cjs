// Build the offline browser payload from the licensed archival maps.
'use strict';
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),{execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..'),source=path.join(root,'assets/materials/wood-veneer');
const catalog=require(path.join(source,'catalog.json'));
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'furnish-wood-veneer-'));
try {
 const materials=catalog.materials.map(({id,name,sampleWidthMm,grainAxis})=>({id,name,materialId:id,sampleWidthMm,grainAxis}));
 const index=new Map(materials.map(material=>[material.id,material]));
 const finishes=catalog.finishes.map(({id,name,materialId,baseColorTintSrgb})=>({
  ...index.get(materialId),id,name,baseColorTintSrgb
 }));
 fs.writeFileSync(path.join(root,'src/data/wood-veneers.js'),
  '/* Generated by scripts/build-wood-veneers.cjs. Stable cabinet surface IDs. */\n'+
  '(function(root){\nconst entries='+JSON.stringify([...materials,...finishes],null,2)+';\n'+
  'if(typeof module==="object"&&module.exports)module.exports=entries;else root.FurnishWoodVeneers=entries;\n'+
  '})(globalThis);\n');
 const payload=Object.fromEntries(catalog.materials.map(material=>[material.id,Object.fromEntries(
  Object.entries(material.maps).map(([role,{file}])=>{
   const output=path.join(temp,role+'.jpg');
   execFileSync('sips',['-Z',(role==='baseColor'?'1024':'512'),'-s','format','jpeg','-s','formatOptions','78',path.join(source,file),'--out',output]);
   return [role,'data:image/jpeg;base64,'+fs.readFileSync(output).toString('base64')];
  })
 )]));
 fs.writeFileSync(path.join(root,'src/data/wood-veneer-textures.js'),
  '/* Generated by scripts/build-wood-veneers.cjs. See assets/materials/wood-veneer for attribution. */\n'+
  'globalThis.FurnishWoodVeneerTextures = '+JSON.stringify(payload,null,2)+';\n');
} finally {fs.rmSync(temp,{recursive:true,force:true});}

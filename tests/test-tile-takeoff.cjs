const layout={width:800,height:800,gap:2,angle:0,origin:[0,0]};
const box=(x,y,X,Y)=>[[x,y],[X,y],[X,Y],[x,Y]];
const room={name:'候选',mat:'tile800',poly:box(0,0,1650,1602)};
const {rows}=H.candidates({floorFinish:{areas:{candidate:{room,layout}},doorways:[],joints:[]}},'candidate',100);
const current=rows.find(r=>r.name==='当前起铺'),balanced=rows.find(r=>r.name==='横向均分');

const [door]=p.floorFinish.joints;
assert.equal(door.key,'door:test-door');
assert(door.aligned&&door.thresholdAvailable&&door.stripAvailable);
assert.throws(()=>F.setDoorJoint(Layers.update(work,'0',{locked:true}),p,door.key,'strip'),/锁定/);
const ordinary=H.report(p,work);

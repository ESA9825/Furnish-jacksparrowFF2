assert.equal(H.summary(current.pieces,46.01).narrow,2);
const split=Z.outline([box(0,0,100,150),box(200,0,300,150)]);
const pieces=H.tilePieces(F.cells(split,layout),layout);
assert.equal(pieces.length,2,'disconnected parts within one lattice cell require two pieces');
const outer=box(0,0,800,800),hole=box(100,100,200,200);
const cut=Z.outline(Z.decompose([outer,hole],p=>Z.inside(p,outer)&&!Z.inside(p,hole)));
const perforated=H.tilePieces(F.cells(cut,layout),layout);
assert.equal(perforated.length,1);
assert.deepEqual([perforated[0].full,perforated[0].rectangle,perforated[0].rings.length],[false,false,2]);
near(perforated[0].area,630000);
